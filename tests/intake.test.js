'use strict';
const assert = require('node:assert/strict');

(async () => {
  const {evaluateEvidence} = await import('../intake/evaluator.js');
  assert.throws(() => evaluateEvidence({text:'  '}), /先粘贴/);
  assert.throws(() => evaluateEvidence({text:'a'.repeat(300001)}), /300,000/);
  const arithmetic = evaluateEvidence({text:'患者缓解 20/100（30%），存在不确定性和不良反应。'});
  assert.equal(arithmetic.summary.confirmedCount, 1);
  assert.match(arithmetic.findings.find(f=>f.status==='confirmed').detail, /20%/);
  assert.match(arithmetic.findings[0].location, /第 1 行/);
  assert.equal(evaluateEvidence({text:'患者 1/3（33%），有不确定性和风险。'}).summary.confirmedCount, 0);
  assert.equal(evaluateEvidence({text:'患者 1/3（33.3%），有不确定性和风险。'}).summary.confirmedCount, 0);
  assert.equal(evaluateEvidence({text:'患者 1/3（33.0%），有不确定性和风险。'}).summary.confirmedCount, 1);
  assert.equal(evaluateEvidence({text:'患者 0/0（0%），有不确定性和风险。'}).summary.confirmedCount, 1);
  assert.equal(evaluateEvidence({text:'与原方案相比增加了120%，患者仍面临风险和不确定性。'}).summary.confirmedCount, 0);
  const refs = evaluateEvidence({text:'研究 DOI:10.1234/ABC.123 重复引文 https://doi.org/10.1234/ABC.123。https://example.org/paper。'});
  assert.equal(refs.references.dois.length, 1);
  assert.equal(refs.references.dois[0].occurrences, 2);
  assert.equal(refs.references.dois[0].verified, false);
  assert.equal(refs.references.verifiedCount, 0);
  assert.ok(!refs.findings.some(f=>/重复研究|重复纳入/.test(f.detail)));
  const highP = evaluateEvidence({text:'差异有统计学意义，p=0.2。'});
  assert.equal(highP.summary.reviewCount, 1);
  assert.equal(highP.summary.confirmedCount, 0);
  assert.equal(evaluateEvidence({text:'差异无统计学意义，p=0.2。'}).summary.reviewCount, 0);
  assert.equal(evaluateEvidence({text:'差异无统计学意义，p=0.01。'}).summary.reviewCount, 1);
  assert.equal(evaluateEvidence({text:'The result was not statistically significant (p=0.2).'}).summary.reviewCount, 0);
  assert.equal(evaluateEvidence({text:'The result was statistically significant (p=0.2).'}).summary.reviewCount, 1);
  const interval = evaluateEvidence({text:'患者显著改善，RR=0.9，95% CI 0.7–1.2。'});
  assert.equal(interval.summary.reviewCount, 1);
  assert.equal(interval.summary.confirmedCount, 0);
  const plain = evaluateEvidence({text:'一种新的方法。'});
  assert.ok(plain.findings.some(f=>f.category==='来源定位' && f.status==='needs_information'));
  assert.ok(plain.checks.some(f=>f.id==='source-support' && f.status==='pending'));
  assert.equal(plain.score, undefined);
  assert.equal(plain.eligible, undefined);
  assert.equal(plain.engine.modelUsed, false);
  assert.ok(!/合格|通过|高质量/.test(plain.summary.headline));
  const partial = evaluateEvidence({text:'读取文字',materials:[{name:'scan.pdf',text:'读取文字',coverage:{status:'partial'}}]});
  assert.equal(partial.coverage.partialMaterials,1);
  assert.ok(partial.findings.some(f=>f.category==='读取范围'));
  const hostile = '<img src=x onerror="globalThis.__executed=true"><script>globalThis.__executed=true</script> 20/100（30%）';
  globalThis.__executed = false;
  const escaped = evaluateEvidence({text:hostile});
  assert.equal(globalThis.__executed,false);
  assert.equal(escaped.summary.confirmedCount,1);
  assert.ok(escaped.findings.some(f=>f.quote.includes('<script>')));
  delete globalThis.__executed;
  const {parseFile, MAX_FILE_BYTES} = await import('../intake/parser.js');
  const parsed = await parseFile(new File(['患者 20/100（30%）\nhttps://example.org'], 'evidence.txt', {type:'text/plain'}));
  assert.equal(parsed.coverage.status,'complete');
  assert.equal(parsed.units[0].startLine,1);
  assert.match(parsed.text,/evidence.txt/);
  assert.match(parsed.text,/20\/100/);
  const truncated = await parseFile(new File(['文字'.repeat(170000)], 'long.txt', {type:'text/plain'}));
  assert.equal(truncated.coverage.status,'partial');
  assert.ok(truncated.text.length<=300000);
  assert.ok(truncated.warnings.some(w=>w.includes('300,000')));
  await assert.rejects(()=>parseFile(new File([''], 'empty.txt')), /文件为空/);
  await assert.rejects(()=>parseFile(new File(['binary'], 'old.xls')), /另存/);
  await assert.rejects(()=>parseFile(new File(['binary'], 'sound.mp3')), /转录/);
  await assert.rejects(()=>parseFile({name:'big.txt',size:MAX_FILE_BYTES+1,arrayBuffer:async()=>new ArrayBuffer(0)}), /20 MB/);
  const hugePNG=new Uint8Array(24);
  const pngView=new DataView(hugePNG.buffer);
  pngView.setUint32(0,0x89504e47);pngView.setUint32(4,0x0d0a1a0a);
  pngView.setUint32(16,9000);pngView.setUint32(20,9000);
  await assert.rejects(()=>parseFile(new File([hugePNG],'huge.png',{type:'image/png'})),/4000 万像素/);
  const fs=require('node:fs'),path=require('node:path');
  for(const extension of ['docx','xlsx']){
    const bytes=fs.readFileSync(path.join(__dirname,'fixtures/intake/synthetic.'+extension));
    const material=await parseFile(new File([bytes],'synthetic.'+extension));
    assert.equal(material.coverage.status,'complete');
    assert.match(material.text,/20\/100 \(30%\)/);
    assert.equal(evaluateEvidence({text:material.text,materials:[material]}).summary.confirmedCount,1);
    if(extension==='xlsx')assert.match(material.text,/B5=0.2/);
  }
  console.log('Intake checks passed: arithmetic, conservative statistical prompts, identifiers, partial reading, no false quality pass, inert hostile text.');
})().catch(error => { console.error(error); process.exitCode=1; });
