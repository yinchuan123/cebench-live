'use strict';
const fs=require('fs'),assert=require('assert');
const {evaluate}=require('../tools/scorer');
const config=JSON.parse(fs.readFileSync(require('path').join(__dirname,'../data/benchmark-config.json'),'utf8'));
const blank=JSON.parse(fs.readFileSync(require('path').join(__dirname,'../data/evaluation-template.json'),'utf8'));
const copy=x=>JSON.parse(JSON.stringify(x));
assert.equal(evaluate(config,blank).score,null);
assert.equal(evaluate(config,blank).eligible,false);
const good=copy(blank);
for(const d of config.dimensions) good.scores[d.id]=80;
for(const g of config.gates) good.gates[g.id]='pass';
Object.assign(good,{actual_run:true,reference_adjudicated:true,dual_review_complete:true,critical_errors:0});
Object.assign(good,{frozen_protocol_id:'fixture-protocol',reference_id:'fixture-reference',reviewers:[{reviewer_id:'A',independent:true,review_record:'fixture-A'},{reviewer_id:'B',independent:true,review_record:'fixture-B'}],metric_observations:config.dimensions.map(d=>({dimension_id:d.id,evidence_location:'fixture-source',review_record:'fixture-review'}))});
assert.equal(evaluate(config,good).score,80);
assert.equal(evaluate(config,good).audit_candidate,true);
assert.equal(evaluate(config,good).eligible,false);
const failure=copy(good);failure.gates.G1='fail';
assert.equal(evaluate(config,failure).eligible,false);
assert.equal(evaluate(config,failure).score,80);
const missing=copy(good);missing.scores.D4=null;
assert.equal(evaluate(config,missing).score,null);
assert.deepEqual(evaluate(config,missing).score_bounds,[64,84]);
const zero=copy(good);zero.scores.D1=0;
assert.equal(evaluate(config,zero).score,68);
const unknown=copy(good);unknown.critical_errors=null;
assert.equal(evaluate(config,unknown).eligible,false);
const invalid=copy(good);invalid.scores.D1=101;
assert.throws(()=>evaluate(config,invalid));
const weights=Object.fromEntries(config.dimensions.map(d=>[d.id,d.weight]));weights.D1=16;
assert.throws(()=>evaluate(config,good,weights));
const unsupported=copy(good);unsupported.track='unknown';assert.throws(()=>evaluate(config,unsupported));
const exploratory=Object.fromEntries(config.dimensions.map(d=>[d.id,config.profiles.core.weights[d.id]]));
assert.equal(evaluate(config,good,exploratory).audit_candidate,false);
const live=copy(good);live.score_profile='live';assert.equal(evaluate(config,live).audit_candidate,false);
const extension=copy(good);extension.track='T5';assert.equal(evaluate(config,extension).audit_candidate,false);
console.log('Scorer checks passed: missing data, true zero, severe error, unreviewed reference, invalid scores/weights/track.');
